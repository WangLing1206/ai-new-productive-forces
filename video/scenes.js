/* ---------------------------------------------------------------- 时长推导 */
const CN = (s) => (s || '').replace(/\s/g, '').length;

function build() {
  let t = 0;
  const out = [];
  SCENES.forEach((s) => {
    const chars = s.nar.reduce((a, c) => a + CN(c), 0);
    const need = Math.round((chars / RATE) * 1000);
    const scrollMs = (s.scroll && s.scroll.dur) || 0;
    const pause = Math.max(MIN_PAUSE, need - scrollMs);
    const dur = scrollMs + pause;
    out.push(Object.assign({}, s, { chars, scrollMs, pauseMs: pause, durMs: dur, startMs: t, endMs: t + dur }));
    t += dur;
  });
  return out;
}

const TIMELINE = build();
const TOTAL_MS = TIMELINE.length ? TIMELINE[TIMELINE.length - 1].endMs : 0;

module.exports = { SCENES, TIMELINE, TOTAL_MS, RATE, CN };

if (require.main === module) {
  console.log('场景数：' + TIMELINE.length);
  TIMELINE.forEach((s) => {
    const mm = (ms) => String(Math.floor(ms / 60000)).padStart(2, '0') + ':' + String(Math.floor(ms % 60000 / 1000)).padStart(2, '0');
    console.log(`${s.id} ${mm(s.startMs)} – ${mm(s.endMs)}  ${String((s.durMs / 1000).toFixed(1)).padStart(5)}s  ${String(s.chars).padStart(3)}字  ${s.name}`);
  });
  const total = TOTAL_MS / 1000;
  const mm = Math.floor(total / 60), ss = Math.floor(total % 60);
  const chars = TIMELINE.reduce((a, s) => a + s.chars, 0);
  console.log(`\n正文总时长 ${mm}分${String(ss).padStart(2, '0')}秒 = ${total.toFixed(1)}s（成片另含片头黑场与片尾淡出）`);
  console.log('总字数 ' + chars + '字，平均语速 ' + (chars / total).toFixed(2) + ' 字/秒');
}
